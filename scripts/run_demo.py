#!/usr/bin/env python3
"""Run the showcase: baseline + cross-pack comparison + gap register. Y.3172: the whole pipeline.

  python scripts/run_demo.py                          # all 3 packs, rule twins, full artefacts
  python scripts/run_demo.py --pack india_current     # one pack only
  python scripts/run_demo.py --tier llm               # LLM agents (needs a populated replay cache)
  python scripts/run_demo.py --ask "Who can order a suspension?"

Writes out/demo_report.md, out/gap_register.csv, out/comparison.json and one ledger per run under
runs/. Every number in the report comes from a run that happened; nothing is hand-entered.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from chakravyuh.agents.adviser import Adviser
from chakravyuh.agents.base import ProposalIdFactory
from chakravyuh.agents.llm_agent import build_llm_agents
from chakravyuh.agents.rule_agents import build_rule_agents
from chakravyuh.analysis.compare import comparison_table, divergences, gap_findings_across, run_across_packs
from chakravyuh.kb.clause_store import ClauseStore
from chakravyuh.analysis.gap_register import register_doc, register_markdown, write_register
from chakravyuh.audit.ledger import verify
from chakravyuh.llm.client import (CacheMiss, LLMClient, LLMUnavailable,
                                   credential_help, missing_credential)
from chakravyuh.policy.compiler import compile_all
from chakravyuh.sim.events import load_scenario

OUT = Path("out")


def agent_factory_for(tier: str, client: LLMClient | None = None):
    if tier == "rule":
        return lambda: build_rule_agents(ProposalIdFactory())
    if tier == "llm":
        client = client or LLMClient()
        return lambda: build_llm_agents(client=client, ids=ProposalIdFactory(), strict=True)
    raise SystemExit(f"unknown agent tier {tier!r}; expected rule|llm")


def preflight(client: LLMClient) -> None:
    """In record/live mode, refuse to start without the credential the model needs.

    A sweep across three packs is many calls; discovering a missing key on the first one wastes
    nothing, but discovering it halfway through a recording leaves a half-populated cache.
    """
    if client.mode == "replay":
        return
    missing = missing_credential(client.model)
    if missing:
        raise SystemExit(credential_help(client.model, missing))


def demo_report(scenario, results, table, divs, findings_by_pack, base_pack: str,
                adviser_qa: list | None = None) -> str:
    lines = [
        "# CHAKRAVYUH demo report (generated by scripts/run_demo.py -- do not edit)",
        "",
        f"Scenario: **{scenario.scenario_id}** - {scenario.title}",
        f"Horizon {scenario.horizon_min} min, {scenario.tick_min}-minute ticks, "
        f"{len(scenario.events)} scripted events "
        f"({sum(1 for e in scenario.events if not e.synthetic)} from the source release, "
        f"{sum(1 for e in scenario.events if e.synthetic)} constructed by us).",
        "",
        "## Limits (read first)",
        "",
        "- **The timeline is real; the network is not.** Every `t_minutes` is computed from the",
        "  timestamps in the IMD RSMC press release on Amphan, and the warned districts are the",
        "  ones that release names. What is constructed is the per-cell state: no public dataset",
        "  records cell-site outage for any Indian cyclone, so cell counts are scaled from",
        "  reported aggregates (COAI: ~8,500 towers / ~36,000 BTS, 65-70% capacity on day 3) and",
        "  the per-cell outages are ours. So are the rumour and the forged order, which are",
        "  adversarial tests and not historical events. Every constructed event carries",
        "  `synthetic: true` and is greyed in the UI.",
        "- Property thresholds are **illustrative**, not legal or engineering standards.",
        "- Policy packs are **encodings of selected clauses for simulation. They are not legal",
        "  advice** and they are not a complete statement of any jurisdiction's law.",
        "- Clause records whose `verbatim_status` is `unverified_summary` carry an accurate summary",
        "  with a real source URL, **not the verbatim text of the instrument**. See `out/kb_report.md`.",
        "- Units are illustrative (cells, minutes, percentages). No money, no casualties, no",
        "  confidence intervals.",
        "",
        "## Properties by pack",
        "",
        "| Pack | " + " | ".join(p.property_id for p in next(iter(results.values())).properties)
        + " | Ledger verifies |",
        "|---|" + "---|" * (len(next(iter(results.values())).properties) + 1),
    ]
    for pack_id in sorted(results):
        r = results[pack_id]
        ok, _ = verify(r.ledger_path)
        cells = " | ".join(
            f"{'PASS' if p.passed else 'FAIL'} ({p.margin:+g})" for p in r.properties)
        lines.append(f"| `{pack_id}` | {cells} | {'yes' if ok else 'NO'} |")

    lines += ["", "Margin is signed slack in each property's own illustrative unit; negative means",
              "violated. Units per property:", ""]
    for p in next(iter(results.values())).properties:
        lines.append(f"- **{p.property_id}**: {p.description} _(unit: {p.unit})_")

    lines += ["", "## Where the packs disagree", ""]
    if divs:
        lines += ["| Property | Fails under | Passes under | Margins |", "|---|---|---|---|"]
        for d in divs:
            margins = ", ".join(f"{k}={v:+g}" for k, v in d["margins"].items())
            lines.append(f"| {d['property_id']} | {', '.join(d['fails_under'])} "
                         f"| {', '.join(d['passes_under'])} | {margins} |")
    else:
        lines.append("_No divergence: every pack reached the same verdict on every property._")

    lines += ["", "## Gap register (domain-first, country as instance)", "",
              register_markdown(findings_by_pack, base_pack), ""]

    counts: dict[str, int] = {}
    for f in findings_by_pack.get(base_pack, []):
        counts[f.gap_class] = counts.get(f.gap_class, 0) + 1
    if counts:
        lines += [f"Gap classes under `{base_pack}`: "
                  + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())), ""]

    lines += ["## Runs", "", "| Pack | Run id | Ticks | Wall (s) | LLM calls | Ledger head |",
              "|---|---|---|---|---|---|"]
    for pack_id in sorted(results):
        r = results[pack_id]
        lines.append(f"| `{pack_id}` | `{r.run_id}` | {r.tick_count} | {r.wall_seconds} "
                     f"| {r.llm_calls} | `{r.ledger_head_hash[:16]}...` |")

    if adviser_qa:
        lines += ["", "## Ask the Adviser", ""]
        for ans in adviser_qa:
            lines += [f"**Q: {ans.question}**", "",
                      f"- mode: `{ans.mode}` (retrieval `{ans.retrieval_mode}`), "
                      f"confidence `{ans.confidence}`",
                      f"- cited clauses: {', '.join(f'`{c}`' for c in ans.cited_clause_ids) or 'none'}",
                      f"- rejected citations: {ans.rejected_citations or 'none'}", "",
                      "```", ans.answer[:1500], "```", ""]
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--scenario", default="data/scenarios/amphan_2020.yaml")
    ap.add_argument("--pack", action="append", help="pack id (repeatable); default all")
    ap.add_argument("--base-pack", default="india_current", help="pack the gap register reports on")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--tier", default="rule", choices=["rule", "llm"])
    ap.add_argument("--model", default=None,
                    help="model id for the LLM tier (overrides CHAKRAVYUH_LOCAL_MODEL)")
    ap.add_argument("--hosted", action="store_true",
                    help="use CHAKRAVYUH_HOSTED_MODEL instead of the local model (showcase run)")
    ap.add_argument("--ask", action="append", help="ask the Adviser a question (repeatable)")
    ap.add_argument("--retrieval-mode", default="hybrid")
    args = ap.parse_args()

    scenario = load_scenario(args.scenario)
    all_packs = compile_all()
    packs = {k: v for k, v in all_packs.items() if not args.pack or k in args.pack}
    if not packs:
        raise SystemExit(f"no pack matched {args.pack}; available: {sorted(all_packs)}")
    base_pack = args.base_pack if args.base_pack in packs else sorted(packs)[0]

    client = None
    if args.tier == "llm" or args.ask:
        client = LLMClient(model=args.model, prefer_hosted=args.hosted)
        preflight(client)

    print(f"scenario {scenario.scenario_id}, packs {sorted(packs)}, tier {args.tier}, "
          f"seed {args.seed}" + (f", model {client.model} ({client.mode})" if client else ""))
    try:
        results = run_across_packs(scenario, packs, seed=args.seed,
                                   agent_factory=agent_factory_for(args.tier, client))
    except CacheMiss as exc:
        print(f"\nLLM replay cache miss: {exc}\n\n"
              f"The demo runs offline in replay mode, so the cache must be populated first:\n"
              f"  CHAKRAVYUH_LLM_MODE=record python scripts/run_demo.py --tier llm\n"
              f"with either OLLAMA_BASE_URL pointing at a local qwen2.5:14b (no API key), or\n"
              f"CHAKRAVYUH_HOSTED_MODEL plus that provider's key, used with --hosted.\n"
              f"Use --tier rule for the deterministic twins, which need no model at all.",
              file=sys.stderr)
        return 3
    except LLMUnavailable as exc:
        print(f"\n{exc}", file=sys.stderr)
        return 3

    for pack_id in sorted(results):
        r = results[pack_id]
        marks = "  ".join(f"{p.property_id}={'PASS' if p.passed else 'FAIL'}({p.margin:+g})"
                          for p in r.properties)
        print(f"  {pack_id:16s} {marks}")

    table = comparison_table(results)
    divs = divergences(results)
    findings = gap_findings_across(results, packs, scenario)

    adviser_qa = []
    if args.ask:
        adviser = Adviser(retrieval_mode=args.retrieval_mode, client=client,
                          use_llm=args.tier == "llm")
        for q in args.ask:
            ans = adviser.ask(q)
            adviser_qa.append(ans)
            print(f"\nQ: {q}\n  mode={ans.mode} cited={ans.cited_clause_ids}")

    OUT.mkdir(parents=True, exist_ok=True)
    # The register's `confidence` column is computed from clause provenance, so it needs the
    # store. Without it every row would read `likely`, which would be wrong in the safe direction
    # but would stop the column meaning anything.
    reg = write_register(findings, packs, base_pack=base_pack, store=ClauseStore(),
                         scenario_id=scenario.scenario_id)
    (OUT / "gap_register.md").write_text(register_doc(reg), encoding="utf-8")
    (OUT / "comparison.json").write_text(json.dumps(
        {"table": table, "divergences": divs,
         "runs": {k: v.model_dump() for k, v in results.items()},
         "gaps": {k: [f.model_dump() for f in v] for k, v in findings.items()}},
        indent=2, sort_keys=True, default=str), encoding="utf-8")
    (OUT / "demo_report.md").write_text(
        demo_report(scenario, results, table, divs, findings, base_pack, adviser_qa), encoding="utf-8")
    print(f"\nwrote {reg}, {OUT / 'gap_register.md'}, {OUT / 'demo_report.md'}, "
          f"{OUT / 'comparison.json'}")

    bad = [r.ledger_path for r in results.values() if not verify(r.ledger_path)[0]]
    if bad:
        print(f"FAIL: ledger verification failed for {bad}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
