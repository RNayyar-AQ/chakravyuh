#!/usr/bin/env python3
"""Export the head of a run ledger as a standalone, self-verifying audit sample. Y.3172 node: SINK.

Why a prefix and not a selection. A hash-chained ledger is verifiable from its first entry
forward, so the first N lines are themselves a valid chain and `verify_ledger.py` accepts the
sample on its own. A hand-picked subset of interesting entries would NOT verify -- the chain
would show gaps -- and a reviewer would have to take our word for it. The prefix is the only
excerpt that keeps the guarantee it is meant to demonstrate.

  python scripts/export_audit_sample.py                     # default run, first 50 entries
  python scripts/export_audit_sample.py --n 200 --run runs/....jsonl
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from chakravyuh.audit.ledger import verify

DEFAULT_RUN = Path("runs/amphan_2020__india_current__rule__seed0.jsonl")
OUT = Path("outputs/audit_sample.jsonl")
INDEX = Path("outputs/audit_sample.md")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run", type=Path, default=DEFAULT_RUN)
    ap.add_argument("--n", type=int, default=50, help="number of leading ledger entries")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()

    if not args.run.exists():
        print(f"no such run: {args.run}; run scripts/run_demo.py first", file=sys.stderr)
        return 2

    ok, msg = verify(args.run)
    if not ok:
        print(f"source ledger does not verify ({msg}); refusing to export", file=sys.stderr)
        return 1

    lines = args.run.read_text(encoding="utf-8").splitlines()[: args.n]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    ok2, msg2 = verify(args.out)
    if not ok2:
        print(f"exported sample does not verify ({msg2}) -- the chain is not prefix-verifiable",
              file=sys.stderr)
        return 1

    kinds: dict[str, int] = {}
    for line in lines:
        kinds[json.loads(line)["kind"]] = kinds.get(json.loads(line)["kind"], 0) + 1

    INDEX.write_text(
        "# Audit sample (generated by scripts/export_audit_sample.py -- do not edit)\n\n"
        f"The first **{len(lines)}** entries of `{args.run.as_posix()}`, exported verbatim.\n\n"
        f"- Verifies on its own: `python scripts/verify_ledger.py {args.out.as_posix()}` -> {msg2}\n"
        f"- Full run: {msg}\n\n"
        "A hash-chained ledger verifies forward from entry 0, so this prefix is a valid chain in\n"
        "its own right. A curated subset of 50 *interesting* entries would not verify, and that\n"
        "is the reason this is a prefix rather than a selection.\n\n"
        "| Entry kind | Count in sample | What it records |\n|---|---|---|\n"
        + "\n".join(f"| `{k}` | {v} | {_KIND_MEANING.get(k, '-')} |"
                    for k, v in sorted(kinds.items()))
        + "\n\nEvery `PROPOSAL` carries `reasoning`, `cited_rule_ids` and `cited_clause_ids`;\n"
          "every `VERDICT` carries the deciding `rule_ids` and `clause_ids`. Nothing in the chain\n"
          "is a summary: these are the records the run actually decided on.\n",
        encoding="utf-8")

    print(f"wrote {args.out} ({len(lines)} entries) and {INDEX}")
    print(f"  sample verifies: {msg2}")
    return 0


_KIND_MEANING = {
    "RUN_HEADER": "scenario, pack, seed, tier -- what makes the run replayable",
    "EVENT": "an exogenous event entering the world, with its ground truth",
    "DELIVERY": "an event arriving at one role, at that role's own time",
    "PROPOSAL": "an agent's proposed action, its reasoning and the law it cites",
    "VERDICT": "the policy engine's decision and the rule that decided it",
    "EFFECT": "what the approved action actually changed in the world",
    "PROPERTY": "a property's PASS/FAIL and signed margin at end of run",
    "LLM_TRACE": "model, prompt hash, retrieved chunks, raw output",
    "HUMAN_DECISION": "approval or refusal of a NEEDS_HUMAN action",
}

if __name__ == "__main__":
    raise SystemExit(main())
