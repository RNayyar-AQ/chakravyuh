"""Y.3172 node vocabulary + registry. Y.3172 node: (meta)."""
from __future__ import annotations

import functools
from enum import Enum


class Y3172Node(str, Enum):
    """ITU-T Y.3172 ML pipeline nodes [Certain: Y.3172 node vocabulary]."""
    SRC = "SRC"
    C = "C"
    PP = "PP"
    M = "M"
    P = "P"
    D = "D"
    SINK = "SINK"


DESCRIPTIONS = {
    Y3172Node.SRC: "Data source: acts, rules, registers, scenario definitions",
    Y3172Node.C: "Collector: ingest of source documents into the knowledge base",
    Y3172Node.PP: "Pre-processor: clause structuring, policy-pack compilation, retrieval",
    Y3172Node.M: "Model: agents that propose actions (LLM or rule-based twins)",
    Y3172Node.P: "Policy: deterministic legality decision over proposals",
    Y3172Node.D: "Distributor: message bus, event release, Game Master resolution",
    Y3172Node.SINK: "Sink: ledger, failure atlas, gap register, UI",
}

REGISTRY: dict[str, list[tuple[str, str, str]]] = {n.value: [] for n in Y3172Node}


def node(which: str | Y3172Node):
    """Tag a function/class with its Y.3172 pipeline node and register it for the map."""
    key = Y3172Node(which).value

    def deco(obj):
        summary = (obj.__doc__ or "").strip().splitlines()[0] if obj.__doc__ else ""
        entry = (obj.__module__, obj.__qualname__, summary)
        if entry not in REGISTRY[key]:
            REGISTRY[key].append(entry)
        obj.__y3172_node__ = key
        if isinstance(obj, type):
            return obj

        @functools.wraps(obj)
        def wrapper(*args, **kwargs):
            return obj(*args, **kwargs)

        wrapper.__y3172_node__ = key
        return wrapper

    return deco


def render_map() -> str:
    """Render REGISTRY as y3172_map.md. Import the package first so decorators have run."""
    lines = [
        "# Y.3172 node map (generated by app/scripts/gen_y3172_map.py -- do not edit)",
        "",
        "CHAKRAVYUH modules mapped onto the ITU-T Y.3172 ML pipeline. This file is generated",
        "from the `@node(...)` decorators in the source, so it cannot drift from the code.",
        "",
        "| Node | Meaning | Module | Entry point | Summary |",
        "|---|---|---|---|---|",
    ]
    for n in Y3172Node:
        entries = sorted(REGISTRY[n.value])
        if not entries:
            lines.append(f"| `{n.value}` | {DESCRIPTIONS[n]} | _(none registered)_ | | |")
            continue
        for i, (mod, qual, summary) in enumerate(entries):
            meaning = DESCRIPTIONS[n] if i == 0 else ""
            label = f"`{n.value}`" if i == 0 else ""
            lines.append(f"| {label} | {meaning} | `{mod}` | `{qual}` | {summary} |")
    lines += [
        "",
        "## Pipeline (spec §5.1)",
        "",
        "```",
        "SRC (acts, rules, register, scenario)",
        "  -> C    kb/ingest.py          (ITU reference ingest -> Chroma; clauses -> SQLite)",
        "  -> PP   policy/compiler.py    (YAML pack -> Rules; verbatim + hash check)",
        "  -> M    agents/*              (LLM or rule twins propose actions)",
        "  -> P    policy/engine.py      (deterministic: ALLOW | BLOCK | NEEDS_HUMAN)",
        "  -> D    sim/bus.py + sim/game_master.py (route events/messages, apply effects)",
        "  -> SINK ledger, failure atlas, gap register, comparison board (Streamlit)",
        "```",
        "",
        "`policy/engine.py` (node P) must not import from `llm/`; `tests/test_engine_purity.py`",
        "fails the build if it ever does.",
        "",
    ]
    return "\n".join(lines)
