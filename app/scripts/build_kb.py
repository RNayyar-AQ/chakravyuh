#!/usr/bin/env python3
"""Build the knowledge base: clause store + chunks + ITU reference Chroma collections.

Y.3172 nodes: SRC -> C. Writes data/clauses/{clauses.jsonl,chunks.jsonl,clauses.sqlite} and
docs/kb_report.md (spec §9.1).

  python app/scripts/build_kb.py                 # clause store + chunks, Chroma if installed
  python app/scripts/build_kb.py --no-chroma     # skip the vector index entirely
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from chakravyuh.kb import ingest
from chakravyuh.kb.clause_store import ClauseStore, DEFAULT_DB
from chakravyuh.policy.compiler import compile_all, compile_report

DOCS = Path("docs")


def kb_report(result: dict, packs_report: dict) -> str:
    integ = result["integrity"]
    chroma = result["chroma"]
    lines = [
        "# Knowledge base report (generated by app/scripts/build_kb.py -- do not edit)",
        "",
        "## Clause store (structured layer)",
        "",
        f"- Clauses: **{integ['total']}**",
        f"- Has a source URL: **{integ['with_source_url']}/{integ['total']}** "
        f"({integ['pct_with_source_url']}%) — *has one*, not *verified against one*; "
        f"see `docs/source_check.md`",
        f"- SHA-256 hash matches stored text: **{integ['hash_matching']}/{integ['total']}** "
        f"({integ['pct_hash_matching']}%)",
        f"- Verbatim text verified against the primary source: "
        f"**{integ['verbatim_verified']}/{integ['total']}** ({integ['pct_verbatim_verified']}%)",
        "",
        "> ## PROVENANCE — read before citing anything",
        ">",
        "> **This corpus is MIXED. Check a record's `provenance` before quoting it.**",
        ">",
        "> - `gazette_pdf` / `gazette_pdf_subsection` — **the instrument's own words**, split from",
        ">   the official eGazette PDF. Each carries its page, a hash of the text, and",
        ">   `source_pdf_sha256`: the hash of the PDF itself, which pins the document even if the",
        ">   link rots. These are safe to quote when `verbatim_status` is `verified`.",
        "> - `verified_with_artifacts` — real text, but the Gazette's marginal section heading is",
        ">   interpolated mid-sentence by a page break. Flagged, excluded from `quotable`, and left",
        ">   uncleaned on purpose: a heuristic fix is ~65% accurate and would mangle statute text.",
        "> - `secondary_source` — a model-written summary whose content claim is attributed to a",
        ">   named secondary source (SCC Online, eCFR, an ITU page). The claim has a citation; the",
        ">   wording is not the instrument's.",
        "> - `model_written` — a model-written summary with **nothing checked**. Section numbers are",
        ">   the likeliest field to be wrong.",
        ">",
        "> Several records are NEGATIVE findings: they assert an instrument is *silent* on",
        "> something. Those carry the highest risk in the corpus and need the full notified text",
        "> to confirm.",
        ">",
        "> What this does NOT affect: exact lookup, the hash chain, the compiler's",
        "> clause-resolution check, the policy engine, the four properties, gap classification,",
        "> cross-pack comparison and the ledger. Every generated result is a true statement about",
        "> *the encoded packs*.",
        ">",
        "> See `data/sources/CLAUSES_PROVENANCE.md` for the verification procedure, the priority",
        "> order, and a table of what the real gazette text caught in the earlier fabricated corpus.",
        "### By provenance",
        "",
        "| Provenance | Clauses |",
        "|---|---|",
    ]
    for prov, n in integ.get("per_provenance", {}).items():
        lines.append(f"| `{prov}` | {n} |")
    lines += [
        "",
        "### By verbatim status",
        "",
        "| Status | Clauses |",
        "|---|---|",
    ]
    for st, n in integ.get("per_verbatim_status", {}).items():
        lines.append(f"| `{st}` | {n} |")
    lines += [
        "",
        f"- Quotable (real text, no page-break artifact): **{integ.get('quotable', 0)}/"
        f"{integ['total']}** ({integ.get('pct_quotable', 0)}%)",
        f"- Carrying a source-PDF hash: **{integ.get('with_source_pdf_hash', 0)}**",
        "",
        "### Clauses per instrument",
        "",
        "| Instrument | Clauses |",
        "|---|---|",
    ]
    for inst, n in integ["per_instrument"].items():
        lines.append(f"| {inst} | {n} |")
    lines += ["", "### Clauses per jurisdiction", "", "| Jurisdiction | Clauses |", "|---|---|"]
    for j, n in integ["per_jurisdiction"].items():
        lines.append(f"| {j} | {n} |")

    lines += [
        "", "## Retrieval layer", "",
        f"- Chunks written: **{result['chunks']}**",
        f"- ChromaDB status: **{chroma['status']}**"
        + (f" ({chroma.get('reason')})" if chroma.get("reason") else ""),
    ]
    if chroma.get("counts"):
        lines += ["", "| ITU reference collection | Documents |", "|---|---|"]
        for name, n in sorted(chroma["counts"].items()):
            lines.append(f"| `{name}` | {n} |")
        lines.append(f"\n- Embedder: `{chroma.get('embedder', 'n/a')}`")
    else:
        lines += ["", "No vector index was built in this run. Retrieval falls back to BM25 over the",
                  "same chunks, so every other component still works; see `docs/retrieval_eval.md`",
                  "for what that costs."]

    lines += [
        "", "### What we add to the ITU reference ingest", "",
        "ITU's reference ingest chunks a source document at roughly 256 words and records no",
        "section metadata: a retrieved chunk can be quoted but not *cited*, because nothing in it",
        "says which provision of which instrument it came from. Every chunk we write into",
        "`kb_main` carries `clause_id`, `instrument`, `jurisdiction`, `page`, `source_url` and",
        "`sha256`, and alongside the chunks we keep one clause-level record per provision holding",
        "the verbatim text and its hash.",
        "",
        "That is the difference between an answer and a checkable answer, and it is what ITU's own",
        "India README asks for when it says to chunk clause-wise for the Acts. It is also what",
        "makes the policy engine possible at all: the engine never retrieves. It fetches clauses by",
        "exact id from the structured store, so no legality decision is ever downstream of a",
        "similarity score.",
        "",
        "## Policy pack compilation", "",
              "Every rule must cite clause IDs that exist in the store and hash-match. A pack that",
              "cites a clause the store does not hold does not compile, so the simulator cannot run",
              "on invented law.", "",
              "| Pack | Jurisdiction | Mode | Rules | Permit | Oblige | Prohibit | Clauses cited | "
              "Rules requiring an authenticated order |",
              "|---|---|---|---|---|---|---|---|---|"]
    for row in packs_report["packs"]:
        lines.append(f"| `{row['pack_id']}` | {row['jurisdiction']} | {row['mode']} | {row['rules']} "
                     f"| {row['permits']} | {row['obligations']} | {row['prohibitions']} "
                     f"| {row['distinct_clauses_cited']} | {row['rules_requiring_authenticated_order']} |")
    lines.append("")
    lines.append("Compiler pass rate: **100%** (a failure raises `PackCompileError` and this report "
                 "is not written).")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--seed-path", default=str(ingest.SEED_PATH))
    ap.add_argument("--db", default=str(DEFAULT_DB))
    ap.add_argument("--no-chroma", action="store_true", help="skip the ChromaDB vector index")
    args = ap.parse_args()

    result = ingest.build(args.seed_path, args.db, push_chroma=not args.no_chroma)
    print(f"clauses: {result['clauses']}  chunks: {result['chunks']}  "
          f"chroma: {result['chroma']['status']}")

    packs = compile_all(store=ClauseStore(args.db))
    report = compile_report(packs.values())
    print(f"packs compiled: {', '.join(sorted(packs))}")

    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "kb_report.md").write_text(kb_report(result, report), encoding="utf-8")
    print(f"wrote {DOCS / 'kb_report.md'}")

    integ = result["integrity"]
    if integ["pct_hash_matching"] < 100.0:
        print("FAIL: not every clause hash-matches its text", file=sys.stderr)
        return 1
    if integ["pct_verbatim_verified"] < 100.0:
        print(f"NOTE: {integ['verbatim_verified']}/{integ['total']} clauses "
              f"({integ['pct_verbatim_verified']}%) carry the instrument's own words; "
              f"{integ['total'] - integ['verbatim_verified']} remain model-written summaries. "
              f"See docs/kb_report.md and data/sources/CLAUSES_PROVENANCE.md.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
