#!/usr/bin/env python3
"""Generate docs/run_stats.md: wall time, tokens and energy proxy per run. Y.3172 node: SINK.

Why this document exists. The brief's eighth perspective is digital infrastructure and energy,
and the usual way to address it is a paragraph claiming efficiency. This measures it instead:
every run records its wall time, its LLM call count and its token usage in the ledger's
RUN_HEADER and in outputs/comparison.json, and the numbers are read back here.

The honest headline is that the deterministic tier costs no tokens at all, which is the actual
engineering claim: the legality decision is code, so the expensive component is optional and is
confined to the Adviser and the optional LLM agent tier.

  python app/scripts/gen_run_stats.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

COMPARISON = Path("outputs/comparison.json")
FUZZ = Path("outputs/fuzz_summary.json")
OUT = Path("docs/run_stats.md")


def main() -> int:
    if not COMPARISON.exists():
        print(f"missing {COMPARISON}; run app/scripts/run_demo.py first", file=sys.stderr)
        return 2
    data = json.loads(COMPARISON.read_text(encoding="utf-8"))
    runs = data.get("runs", {})
    if not runs:
        print("comparison.json has no runs", file=sys.stderr)
        return 1

    rows = []
    for pack, r in sorted(runs.items()):
        rows.append({
            "pack": pack,
            "run_id": r.get("run_id", ""),
            "ticks": int(r.get("tick_count", 0) or 0),
            "wall_s": float(r.get("wall_seconds", 0.0) or 0.0),
            "llm_calls": int(r.get("llm_calls", 0) or 0),
            "tokens": int(r.get("llm_tokens", 0) or 0),
            "head": (r.get("ledger_head_hash") or "")[:16],
        })
    total_wall = sum(r["wall_s"] for r in rows)
    total_tokens = sum(r["tokens"] for r in rows)
    total_calls = sum(r["llm_calls"] for r in rows)
    total_ticks = sum(r["ticks"] for r in rows)

    lines = [
        "# Run cost (generated by app/scripts/gen_run_stats.py -- do not edit)",
        "",
        f"**{len(rows)} runs · {total_ticks} ticks · {total_wall:.3f} s of compute · "
        f"{total_calls} LLM calls · {total_tokens} tokens.**",
        "",
        "| Pack | Ticks | Wall (s) | ms/tick | LLM calls | Tokens | Ledger head |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        per_tick = (r["wall_s"] / r["ticks"] * 1000) if r["ticks"] else 0.0
        lines.append(f"| `{r['pack']}` | {r['ticks']} | {r['wall_s']:.4f} | {per_tick:.3f} "
                     f"| {r['llm_calls']} | {r['tokens']} | `{r['head']}…` |")

    if FUZZ.exists():
        fuzz = json.loads(FUZZ.read_text(encoding="utf-8"))
        campaigns = fuzz if isinstance(fuzz, list) else fuzz.get("campaigns", [])
        if campaigns:
            lines += ["", "## Fuzzing campaigns", "",
                      "| Properties asserted | Wall (s) | Unique minimal failures |",
                      "|---|---|---|"]
            for c in campaigns:
                lines.append(f"| {', '.join(c.get('asserted_properties', []))} "
                             f"| {float(c.get('wall_seconds', 0)):.2f} "
                             f"| {len(c.get('cards', []))} |")

    lines += [
        "",
        "## What these numbers mean",
        "",
        f"- **The deterministic tier costs {total_tokens} tokens.** Agent twins, the policy",
        "  engine, the clause store, the properties, the gap classifier and the fuzzer all run",
        "  with no model and no network. That is not an optimisation; it is the architecture. The",
        "  legality decision is a pure function (ITU-T Y.3172 node **P**), so a 125-hour cyclone",
        "  replays across three legal regimes for the energy cost of a page load.",
        "- **A full three-pack sweep is "
        f"{total_wall:.2f} s.** This is what makes policy *fuzzing* possible at all: a campaign",
        "  that mutates the scenario hundreds of times is only affordable because one run is",
        "  effectively free.",
        "- **Tokens appear only where a model is genuinely needed** — the Adviser's free-text",
        "  answers, and the optional `--tier llm` agents. Both are recorded per call in the",
        "  ledger as `LLM_TRACE` with a prompt hash, and both are served from the replay cache",
        "  during a demo, so a demo run adds zero further inference.",
        "- **Measured, not modelled.** Wall time is `time.perf_counter()` around the run loop and",
        "  token counts come from the provider's own usage field. There is no joules estimate",
        "  here: converting seconds to energy needs the host's power draw, which we do not have,",
        "  and a fabricated watt figure would be worth less than the seconds.",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}: {len(rows)} runs, {total_wall:.3f} s, {total_tokens} tokens")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
